"""Two-level memory of verified corrections: why a description failed, what repaired it, where the repair holds.

Level 1 is the existing move library of `learning.py`: each verified correction keeps its monomial support and the
evidence of its withheld test. Such a recipe is tied to the source and target dimensions in which it was found and
reuses its support literally.

Level 2 abstracts a verified correction into a repair family by asking why the proposed description failed. For
source dynamics F, retained observables h and proposed evolution G, the defect is

    R = Dh F - G(h).

Its position relative to the algebra generated by the retained observables decides the family. Reduce R modulo a
lexicographic Groebner basis of {z_i - h_i(x)} with the source coordinates ordered first; R lies in the subalgebra
R[h] exactly when the remainder r(z) is free of source coordinates (subalgebra membership).

  closure_in_retained_coordinates   r(z) free of x: the retained coordinates close and G lacks terms, G -> G + r(z).
      Subtypes: a state-free r (the drift of a moving coordinate frame), terms of higher degree than G (missing
      saturation) and terms of lower or equal degree (a missing interaction).
  omitted_state_variable            r depends on x: the retained coordinates do not determine their own evolution.
      The repair adds the monomials of the remainder as coordinates and repeats the reduction on their Lie derivatives
      until the enlarged set closes (a finite tower), or the budget of added coordinates is exhausted.

A family enters the library only after a correction of its kind has passed the identity check and the withheld
trajectories in `learning.learn`. Each family carries its mathematical assumptions, the corrections that succeeded
under it and its counterexamples. The classification algorithms are supplied mathematical procedures. Experience
stores successful supports and conditions on their reuse; a direct-symbolic baseline measures the supplied
algorithms without memory. All strategies use the verifier and withheld registry in `learning.learn`.
Revision suppresses a failed hint on its equation task and optional search policy; a search limit is not a proof
of physical impossibility.

Candidate evaluations count identity solves exactly as `learning.learn` does. The symbolic classification (one
Groebner reduction per tower level) is reported separately.
"""
from __future__ import annotations

import copy
import hashlib
import json
from dataclasses import asdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import sympy as sp

from . import learning as ln

SCHEMA = "fieldbridge-repair-families/1"

ASSUMPTIONS = {
    "closure_in_retained_coordinates": [
        "autonomous deterministic polynomial source dynamics on a Euclidean carrier",
        "the defect Dh F - G(h) lies in the algebra generated by the retained observables",
    ],
    "omitted_state_variable": [
        "autonomous deterministic polynomial source dynamics on a Euclidean carrier",
        "the defect leaves the algebra of the retained observables",
        "the Lie derivatives of the added monomials close within the budget of added coordinates",
    ],
}


# ------------------------------------------------------------------------------------------- classification
def _domain(p):
    return sp.QQ.frac_field(*p) if p else sp.QQ


def reduce_in_subalgebra(expr, x, h, p) -> Tuple[sp.Expr, sp.Expr, List[sp.Symbol]]:
    """Remainder of expr modulo the lex Groebner basis of {z_i - h_i(x)}, x > z. Returns (remainder, remainder
    with z substituted back by h, z symbols). The remainder is free of x iff expr lies in the subalgebra R[h]."""
    z = [sp.Dummy(f"z{i}", real=True) for i in range(len(h))]
    gens = list(x) + z
    G = sp.groebner([zi - hi for zi, hi in zip(z, h)], *gens, order="lex", domain=_domain(p))
    _, rem = G.reduce(sp.expand(expr))
    rem = sp.expand(rem)
    return rem, sp.expand(rem.subs(dict(zip(z, h)))), z


def classify(task: Dict) -> Dict[str, object]:
    """The family of the defect of a learning task, from the equations alone."""
    real, x, p, F, z, h, G = ln._parse_task(task)
    residual = ln._residual(x, F, z, h, G)
    if all(sp.simplify(r) == 0 for r in residual):
        return {"family": "already_closed", "residual": [], "groebner_reductions": 0}
    reductions, inside, components = 0, True, []
    for zi, r in zip(z, residual):
        rem, _, tags = reduce_in_subalgebra(r, x, h, p)
        reductions += 1
        free = not rem.free_symbols.intersection(x)
        inside &= free
        rem_z = sp.expand(rem.subs(dict(zip(tags, z)))) if free else None
        components.append({"coordinate": str(zi), "residual": str(r), "remainder": str(rem),
                           "in_retained_algebra": bool(free),
                           "remainder_in_retained": None if rem_z is None else str(rem_z)})
    out: Dict[str, object] = {"residual": list(map(str, residual)), "components": components,
                              "groebner_reductions": reductions}
    if inside:
        degs_g = [sp.Poly(g, *z).total_degree() if g != 0 else 0 for g in G]
        rems = [sp.sympify(c["remainder_in_retained"], locals={str(s): s for s in z + p}) for c in components]
        state_free = all(not sp.sympify(r).free_symbols.intersection(z) for r in rems)
        deg_r = max((sp.Poly(r, *z).total_degree() for r in rems if r != 0), default=0)
        subtype = ("moving_frame_drift" if state_free else
                   "missing_saturation" if deg_r > max(degs_g) else "missing_interaction")
        out.update(family="closure_in_retained_coordinates", subtype=subtype, remainder_degree=int(deg_r))
    else:
        out.update(family="omitted_state_variable")
    return out


def _monomials_in(expr, x) -> List[Tuple[int, ...]]:
    return [m for m in sp.Poly(sp.expand(expr), *x).monoms() if sum(m) > 0]


def omitted_tower(task: Dict, max_added: int) -> Dict[str, object]:
    """Close the retained observables by adding the monomials of successive remainders (a finite tower)."""
    real, x, p, F, z, h, G = ln._parse_task(task)
    H = list(h)
    added: List[Tuple[int, ...]] = []
    levels, reductions = [], 0
    frontier = list(h)
    while True:
        new: List[Tuple[int, ...]] = []
        for obs in frontier:
            lie = sp.expand(sum(sp.diff(obs, v) * f for v, f in zip(x, F)))
            rem, _, _ = reduce_in_subalgebra(lie, x, H, p)
            reductions += 1
            if rem.free_symbols.intersection(x):
                # Retained observables are coefficients here: z*y still requires the discarded factor y.
                for m in _monomials_in(rem, x):
                    mono = ln._monomial(x, m)
                    if m not in added and m not in new and all(sp.simplify(mono - o) != 0 for o in H):
                        new.append(m)
        if not new:
            # degree of the closed evolution in the enlarged coordinates
            degree = 1
            for obs in H:
                lie = sp.expand(sum(sp.diff(obs, v) * f for v, f in zip(x, F)))
                rem, _, tags = reduce_in_subalgebra(lie, x, H, p)
                reductions += 1
                if rem.free_symbols.intersection(x):
                    return {"closed": False, "added": [list(m) for m in added], "levels": levels,
                            "groebner_reductions": reductions, "reason": "unresolved discarded coordinate"}
                if rem != 0:
                    degree = max(degree, sp.Poly(rem, *tags).total_degree())
            return {"closed": True, "added": [list(m) for m in added], "levels": levels, "degree": int(degree),
                    "groebner_reductions": reductions}
        levels.append([str(ln._monomial(x, m)) for m in new])
        if len(added) + len(new) > max_added:
            return {"closed": False, "added": [list(m) for m in added], "levels": levels,
                    "groebner_reductions": reductions,
                    "reason": f"the tower needs more than {max_added} added coordinates"}
        added += new
        H += [ln._monomial(x, m) for m in new]
        frontier = [ln._monomial(x, m) for m in new]


# ------------------------------------------------------------------------------------------------- library
class FamilyLibrary:
    """JSON record of repair families. `frozen` forbids every change; revision happens through `revise`."""

    def __init__(self, path: Optional[Path] = None, frozen: bool = False):
        self.path = Path(path) if path else None
        self.frozen = frozen
        self._data = {"schema": SCHEMA, "families": {}}
        if self.path and self.path.exists():
            self._data = json.loads(self.path.read_text())
        if self._data.get("schema") != SCHEMA or not isinstance(self._data.get("families"), dict):
            raise ValueError("Invalid repair-family library")

    @property
    def data(self):
        return copy.deepcopy(self._data)

    def digest(self) -> str:
        return ln.digest(self._data)

    def save(self):
        if self.frozen:
            raise RuntimeError("the family library is frozen")
        if self.path:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            temporary = self.path.with_suffix(self.path.suffix + ".tmp")
            temporary.write_text(json.dumps(self._data, indent=2, allow_nan=False) + "\n")
            temporary.replace(self.path)

    def families(self) -> Dict[str, Dict]:
        return copy.deepcopy(self._data["families"])

    def abstract(self, task: Dict, report: Dict, label: str) -> Optional[str]:
        """Enter a verified correction into its family (level 1 -> level 2)."""
        if self.frozen:
            raise RuntimeError("the family library is frozen")
        if (report.get("status") != "verified_extension" or report.get("input_sha256") != ln.digest(task)
                or not report.get("withheld", {}).get("passed")
                or not ln.verify_identity(task, report["candidate"])["passed"]):
            return None
        cls = classify(task)
        fam = cls["family"]
        if fam not in ASSUMPTIONS:
            return None
        rec = self._data["families"].setdefault(fam, {"assumptions": list(ASSUMPTIONS[fam]), "successes": [],
                                                     "counterexamples": [], "subtypes": {}, "guards": []})
        added = report["candidate"]["recipe"].get("extra_powers", [])
        rec["successes"].append({"task": label, "task_sha256": ln.digest(task), "subtype": cls.get("subtype"),
                                 "source_dimension": len(task["model"]["carrier"]["variables"]),
                                 "retained_dimension": len(task["coordinates"]),
                                 "added_coordinates": len(added),
                                 "recipe": copy.deepcopy(report["candidate"]["recipe"]),
                                 "candidate_sha256": report["candidate_sha256"],
                                 "withheld_error": report["withheld"]["max_error"],
                                 "omission_error": report["withheld"]["max_omission_error"]})
        if cls.get("subtype"):
            rec["subtypes"][cls["subtype"]] = rec["subtypes"].get(cls["subtype"], 0) + 1
        self.save()
        return fam

    def revise(self, label: str, task: Dict, family: str, reason: str, *, policy=None):
        """Stop reusing a failed hint on this equation task; policy-specific failures remain policy-specific."""
        if self.frozen:
            raise RuntimeError("the family library is frozen")
        rec = self._data["families"][family]
        rec["counterexamples"].append({"task": label, "task_sha256": ln.digest(task), "reason": reason})
        guard = {"kind": "skip_task_guidance", "task_key": task_key(task),
                 "policy": asdict(policy) if policy else None, "reason": reason}
        if guard not in rec.setdefault("guards", []):
            rec["guards"].append(guard)
        self.save()


def task_key(task):
    """Equation-level key: intervention labels and outcomes cannot alter a hint's applicability."""
    _, x, p, F, z, h, G = ln._parse_task(task)
    rename = {s: sp.Symbol(f"v{i}") for i, s in enumerate(x + p + z)}
    return ln.digest({"source": [str(f.xreplace(rename)) for f in F],
                      "observables": [str(f.xreplace(rename)) for f in h],
                      "proposed": [str(f.xreplace(rename)) for f in G]})


# --------------------------------------------------------------------------------------------- construction
def _symbolic_proposals(task: Dict, policy: ln.Policy):
    """The direct symbolic solver, without any experience or library gate."""
    cls = classify(task)
    info = {"classification": cls, "groebner_reductions": cls.get("groebner_reductions", 0), "proposed_by": []}
    fam = cls["family"]
    if fam == "already_closed":
        return info, []
    real, x, p, F, z, h, G = ln._parse_task(task)
    if fam == "closure_in_retained_coordinates":
        powers = set()
        for c in cls["components"]:
            r = sp.sympify(c["remainder_in_retained"], locals={str(s): s for s in z + p})
            if r != 0:
                powers.update(sp.Poly(r, *z).monoms())
        info["proposed_by"].append(fam)
        return info, [([], sorted(powers))]
    tower = omitted_tower(task, policy.max_added_coordinates)
    info["groebner_reductions"] += tower["groebner_reductions"]
    info["tower"] = tower
    if not tower["closed"]:
        return info, []
    extra = [tuple(m) for m in tower["added"]]
    powers = list(ln._powers(len(z) + len(extra), tower["degree"]))
    info["proposed_by"].append(fam)
    return info, [(extra, powers)]


def _proposals(task: Dict, library: FamilyLibrary, policy: ln.Policy, *, derive=True):
    cls = classify(task)
    fam = cls["family"]
    info = {"classification": cls, "groebner_reductions": cls.get("groebner_reductions", 0), "proposed_by": []}
    rec = library.families().get(fam)
    if not rec or not rec.get("successes"):
        return info, []
    for guard in rec.get("guards", []):
        if (guard["kind"] == "skip_task_guidance" and guard["task_key"] == task_key(task)
                and (guard["policy"] is None or guard["policy"] == asdict(policy))):
            return {**info, "guidance_skipped": guard}, []
    _, x, _, _, z, _, _ = ln._parse_task(task)
    proposals = []
    seen = set()
    for success in rec["successes"]:
        recipe = success.get("recipe", {})
        extra, powers = recipe.get("extra_powers", []), recipe.get("powers", [])
        if recipe.get("source_dimension") == len(x) and recipe.get("original_dimension") == len(z):
            key = ln.digest([extra, powers])
            if key not in seen and ln._valid_proposal(extra, powers, len(x), len(z), policy):
                proposals.append((extra, powers))
                seen.add(key)
    stored_count = len(proposals)
    info["stored_recipe_count"] = stored_count
    info["family_available"] = True
    if not derive:
        return info, proposals
    symbolic, derived = _symbolic_proposals(task, policy)
    info["groebner_reductions"] += symbolic["groebner_reductions"]
    info.update({k: v for k, v in symbolic.items() if k not in {"groebner_reductions", "classification"}})
    for extra, powers in derived:
        key = ln.digest([extra, powers])
        if key not in seen:
            proposals.append((extra, powers))
            seen.add(key)
    return info, proposals


def construct(task: Dict, library: Optional[FamilyLibrary] = None, policy: Optional[ln.Policy] = None,
              *, evaluation_library=None, strategy="families") -> Dict:
    """Propose with experience or direct algebra; use the same verifier and test registry for both."""
    if strategy not in {"families", "symbolic"}:
        raise ValueError("strategy must be families or symbolic")
    if evaluation_library is None and library is not None and library.path is not None:
        evaluation_library = ln.MoveLibrary(library.path.with_suffix(".evaluations.sqlite"))
    snapshot = library.digest() if library else None

    def propose(t, limits, report):
        if strategy == "symbolic":
            info, props = _symbolic_proposals(t, limits)
        elif library is not None:
            info, props = _proposals(t, library, limits, derive=False)
        else:
            info, props = {}, []
        report.update(family_analysis=info, groebner_reductions=info.get("groebner_reductions", 0),
                      family_library_sha256=snapshot, strategy=strategy,
                      proposer_implementation_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
        seen = set()
        for extra, powers in props:
            seen.add(ln.digest([extra, powers]))
            yield strategy, None, extra, powers
        if strategy == "families" and info.get("family_available"):
            derived_info, derived_props = _symbolic_proposals(t, limits)
            reductions = info.get("groebner_reductions", 0) + derived_info.get("groebner_reductions", 0)
            info.update(derived_info, groebner_reductions=reductions)
            report["groebner_reductions"] = reductions
            for extra, powers in derived_props:
                key = ln.digest([extra, powers])
                if key not in seen:
                    seen.add(key)
                    yield strategy, None, extra, powers
        _, x, _, F, z, h, G = ln._parse_task(t)
        residual = ln._residual(x, F, z, h, G)
        for candidate in ln._recipes(x, z, h, residual, limits, None):
            key = ln.digest([candidate[2], candidate[3]])
            if key not in seen:
                seen.add(key)
                yield candidate

    report = ln.learn(task, evaluation_library, policy, proposer=propose)
    if library is not None and library.digest() != snapshot:
        raise RuntimeError("Family library changed during construction")
    return report


def repair_departures(evaluations: ln.MoveLibrary, families: FamilyLibrary, policy=None):
    """Consume recorded equation tasks once; unsupported departures retain a concrete next requirement."""
    if families.frozen:
        raise RuntimeError("Repair campaigns require a mutable learning library")
    rows = []
    for key, departure in evaluations.departures():
        old = evaluations.campaign(key)
        if old is not None:
            rows.append({"departure": key, "status": "campaign_in_progress" if old["status"] == "running"
                         else "already_processed", "previous_status": old["status"]})
            continue
        task = departure.get("learning_task")
        if not isinstance(task, dict):
            rows.append({"departure": key, "status": "needs_equation_task",
                         "required": ["coordinates", "candidate_drift", "development", "withheld"]})
            continue
        if task.get("model") != departure.get("model"):
            rows.append({"departure": key, "status": "source_mismatch"})
            continue
        if not evaluations.claim_campaign(key):
            rows.append({"departure": key, "status": "already_claimed"})
            continue
        report = construct(task, families, policy, evaluation_library=evaluations)
        if report["status"] == "verified_extension":
            report["retained_family"] = families.abstract(task, report, key)
        elif report["status"] in {"unresolved", "search_budget_exhausted"} and (
                report.get("family_analysis", {}).get("classification", {}).get("family") in families.families()):
            fam = report["family_analysis"]["classification"]["family"]
            families.revise(key, task, fam, report["status"], policy=policy or ln.Policy())
        evaluations.store_campaign(key, report)
        rows.append({"departure": key, **report})
    return rows

